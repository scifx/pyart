#!/usr/bin/env python3
"""Compare Pyart's builtin implementations with Arturo's src/library modules.

Run against a pinned Arturo source checkout:

    python3 tools/audit_upstream_library.py /path/to/arturo/src/library \
        --revision 4e549e105c54af2e250381d578474b9064d9d4d2

The report lists every upstream `builtin` declaration and whether Pyart has a
registered implementation. `Ui.nim` is displayed but excluded from the
non-UI completion totals.
"""
from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DECL = re.compile(r'\bbuiltin\s+"([^"]+)"')
EXAMPLE = re.compile(r'\bexample\s*=\s*"""(.*?)"""\s*:', re.S)


def imports_of(text: str) -> list[str]:
    # Restrict extraction to the file's import section; examples and comments
    # can themselves contain the word `import`.
    start = text.find("# Libraries")
    end = text.find("# Definitions", start + 1)
    section = text[start:end] if start >= 0 and end >= 0 else ""
    found = []
    for line in section.splitlines():
        stripped = line.strip()
        if stripped.startswith("import "):
            found.append(stripped.removeprefix("import "))
    return list(dict.fromkeys(found))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source_dir", type=Path)
    parser.add_argument("--revision", default="unknown")
    parser.add_argument("--output", type=Path,
                        default=Path("docs/ARTURO_PORT_PLAN.md"))
    args = parser.parse_args()
    source_dir = args.source_dir

    from arturo.builtins import REGISTRY
    from arturo.signatures import SIGNATURES
    metadata_path = ROOT / "arturo" / "builtin_docs.json"
    source_metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    # Import registration modules before reading their decorators.
    importlib.import_module("arturo.builtins.core")
    importlib.import_module("arturo.builtins.collections")
    importlib.import_module("arturo.builtins.strings")
    importlib.import_module("arturo.builtins.iterators")
    importlib.import_module("arturo.builtins.numbers")
    importlib.import_module("arturo.builtins.misc")
    importlib.import_module("arturo.builtins.dates")

    modules = []
    for path in sorted(source_dir.glob("*.nim")):
        text = path.read_text(encoding="utf-8", errors="replace")
        names = list(dict.fromkeys(DECL.findall(text)))
        examples = len(EXAMPLE.findall(text))
        implemented = [name for name in names if name in REGISTRY]
        modules.append((path.stem, names, implemented, examples, imports_of(text)))

    signature_mismatches = []
    for name, doc in source_metadata.items():
        local = SIGNATURES.get(name)
        source_arity = len(doc.get("args", []))
        source_attrs = {a["name"] for a in doc.get("attrs", [])}
        if local is None:
            signature_mismatches.append((name, "missing local declaration"))
            continue
        local_arity, local_attrs, _module = local
        differences = []
        if local_arity != source_arity:
            differences.append(f"arity source={source_arity} local={local_arity}")
        if set(local_attrs) != source_attrs:
            differences.append(
                f"attrs source={sorted(source_attrs)} local={sorted(local_attrs)}"
            )
        if differences:
            signature_mismatches.append((name, "; ".join(differences)))

    non_ui = [row for row in modules if row[0] != "Ui"]
    total = sum(len(row[1]) for row in non_ui)
    done = sum(len(row[2]) for row in non_ui)
    example_total = sum(row[3] for row in non_ui)

    lines = [
        "# Arturo upstream library port audit",
        "",
        f"_Source: `arturo-lang/arturo` `{args.revision}`, `src/library/*.nim`._",
        "Generated by `tools/audit_upstream_library.py`; UI is inventoried but excluded from completion scope._",
        "",
        "## Scope and snapshot",
        "",
        f"- Source modules: **{len(modules)}**; non-UI modules: **{len(non_ui)}**.",
        f"- Upstream `builtin` declarations in non-UI modules: **{total}**.",
        f"- Registered Python implementations matching those declarations: **{done}/{total}**.",
        f"- Statically declared non-UI source example blocks: **{example_total}**. These still need execution and output-differential validation.",
        f"- Source parameter arity and accepted-attribute metadata match the local signature table for **{len(source_metadata) - len(signature_mismatches)}/{len(source_metadata)}** snapshot entries.",
        "- The broader Pyart registry also contains generated predicates, translated aliases and legacy names; it is not interchangeable with this source declaration count.",
        "",
        "## Dependency order",
        "",
        "1. **Execution and syntax contracts:** parser/AST/evaluator, value types, arity and attribute dispatch, function/method calls, `->`/`=>` blocks, paths, error/return/break semantics, and quantity literals. Every builtin example depends on this layer.",
        "2. **Foundational library contracts:** `Types`, `Core`, `Exceptions`, `Logic`, `Comparison`, `Arithmetic`, `Bitwise`, and `Reflection`. They define conversions, control flow, function metadata, attribute behavior and runtime inspection used by nearly every module.",
        "3. **Pure/value modules:** `Collections`, `Sets`, `Strings`, `Numbers`, `Statistics`, `Iterators`, `Dates`, `Quantities`, `Colors`, and `Crypto`. Implement their shared value/iteration/conversion contracts before relying on examples from later modules.",
        "4. **Host/runtime integrations:** `Paths`, `Files`, `Io`, `System`, `Databases`, `Net`, `Streams`, `Tasks`, and `Events`. These need explicit cwd/env/process/error policies and resource-lifetime tests. They are in scope; only `Ui.nim` is deferred.",
        "",
        "## Syntax-sensitive areas to lock down before broad porting",
        "",
        "- Arity-driven prefix calls and right-to-left argument evaluation; infix grouping and dynamically registered infix aliases.",
        "- Pending attributes (`.get`, `.with: value`) and non-consuming `attr?`; attributes must survive exactly until the target builtin consumes them.",
        "- `->` block capture versus `=>` implicit parameters (`&`, `__`), block evaluation versus literal block data, and unscoped/collector execution (`@[]`).",
        "- Word/literal/symbol/path-literal distinctions; dictionary/object paths and method lookup; typed function parameters and `;;` data comments.",
        "- Quantity suffix/colon syntax and unit-family conversion; errors, `return`, `break`, and `continue` through nested calls.",
        "- System path resolution, cwd changes, argv parsing, child-process status/stdout/stderr, async/task/stream cleanup and OS error translation.",
        "",
        "## Module-by-module declarations and current coverage",
        "",
        "| Upstream module | Declared | Implemented | Missing | Example blocks | Python imports / dependencies visible in Nim source |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for module, names, implemented, examples, imports in modules:
        missing = [name for name in names if name not in REGISTRY]
        deps = "; ".join(imports).replace("|", "\\|") or "—"
        lines.append(
            f"| `{module}.nim` | {len(names)} | {len(implemented)} | {len(missing)} | {examples} | {deps} |"
        )
    lines += ["", "## Source signature alignment", ""]
    if signature_mismatches:
        lines.append(f"Mismatches: **{len(signature_mismatches)}**")
        lines.extend(f"- `{name}` — {detail}" for name, detail in signature_mismatches)
    else:
        lines.append(
            f"All **{len(source_metadata)}** static builtin declarations match the source snapshot on argument arity and accepted attribute names."
        )
    lines += ["", "## Function inventory", ""]
    for module, names, implemented, examples, imports in modules:
        missing = [name for name in names if name not in REGISTRY]
        lines.append(f"### {module}.nim ({len(implemented)}/{len(names)} implemented)")
        lines.append("")
        lines.append("- Declared: " + (", ".join(f"`{name}`" for name in names) or "(none)"))
        if missing:
            lines.append("- Missing/stub: " + ", ".join(f"`{name}`" for name in missing))
        else:
            lines.append("- Missing/stub: none")
        lines.append("")
    lines += [
        "## Completion gate",
        "",
        "A source `builtin` is complete only when its upstream argument and attribute semantics, return type, side effects, errors, and example outputs match. A registered decorator alone does not count: placeholder results (for example, a permanently empty stack) must be treated as incomplete. Run all available upstream example blocks independently and compare output against Arturo at the same revision; record platform-dependent exclusions rather than silently skipping them.",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.output}: {done}/{total} non-UI declarations implemented")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
